"""Scan Gmail, turn matching emails into staged receipt PDFs.

Nothing here leaves the machine except the Gmail reads and whatever a fetcher
does on the vendor's own site. Staged receipts sit in the database until the
review screen exports them.
"""

from __future__ import annotations

import logging
