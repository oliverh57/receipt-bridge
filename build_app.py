def build_icon(resources: Path) -> bool:
    """Render an app icon with the Chromium we already depend on."""
    try:
        from playwright.sync_api import sync_playwright
    except ImportError:
        return False

    iconset = resources.parent / "icon.iconset"
    png = resources.parent / "icon-1024.png"
    try:
        with sync_playwright() as p:
            browser = p.chromium.launch()
            page = browser.new_page(viewport={"width": 1024, "height": 1024})
            page.set_content(ICON_HTML)
            page.screenshot(path=str(png))
            browser.close()

        iconset.mkdir(parents=True, exist_ok=True)
        for size in (16, 32, 64, 128, 256, 512):
            for scale, suffix in ((1, ""), (2, "@2x")):
                out = iconset / f"icon_{size}x{size}{suffix}.png"
                subprocess.run(
                    ["sips", "-z", str(size * scale), str(size * scale),
                     str(png), "--out", str(out)],
                    check=True, capture_output=True,
                )
        subprocess.run(
            ["iconutil", "-c", "icns", str(iconset),
             "-o", str(resources / "icon.icns")],
            check=True, capture_output=True,
        )
        return True
    except Exception as exc:
        print(f"  (skipping icon: {exc})")
        return False
    finally:
        shutil.rmtree(iconset, ignore_errors=True)
        png.unlink(missing_ok=True)


def build(destination: Path) -> Path:
    bundle = destination / f"{APP_NAME}.app"
    if bundle.exists():
        shutil.rmtree(bundle)

    macos = bundle / "Contents" / "MacOS"
    resources = bundle / "Contents" / "Resources"
    macos.mkdir(parents=True)
    resources.mkdir(parents=True)

    print(f"Building {bundle}")
    has_icon = build_icon(resources)

    # app/updates.py is the one place the version is written down. Read, not
    # imported, so building doesn't need the app's dependencies.
    found = re.search(r'^VERSION = "([^"]+)"', (ROOT / "app" / "updates.py").read_text(encoding="utf-8"), re.M)
    version = found.group(1) if found else "1.0.0"

    info = {
        "CFBundleName": APP_NAME,
        "CFBundleDisplayName": APP_NAME,
        "CFBundleIdentifier": BUNDLE_ID,
        "CFBundleVersion": version,
        "CFBundleShortVersionString": version,
        "CFBundleExecutable": EXECUTABLE,
        "CFBundlePackageType": "APPL",
        "NSHighResolutionCapable": True,
        # A regular app: Dock icon, menu bar, Cmd-Tab.
        "LSUIElement": False,
        "LSMinimumSystemVersion": "11.0",
    }
    if has_icon:
        info["CFBundleIconFile"] = "icon"

    with (bundle / "Contents" / "Info.plist").open("wb") as handle:
        plistlib.dump(info, handle)

    launcher = macos / EXECUTABLE
    (ROOT / "data").mkdir(exist_ok=True)
    if not compile_launcher(launcher):
        launcher.write_text(
            LAUNCHER.format(app_name=APP_NAME, project=ROOT), encoding="utf-8"
        )
        launcher.chmod(0o755)

    sign(bundle)
    return bundle


def sign(bundle: Path) -> None:
    """Ad-hoc sign the bundle so macOS treats it as a stable app identity.

    Without a signature, TCC silently returns "Operation not permitted" when
    the app touches a protected folder such as ~/Documents — no prompt, no
    error, just an app that appears to start and then does nothing. Signing
    makes macOS show the normal "would like to access" dialog instead.
    """
    result = subprocess.run(
        ["codesign", "--force", "--deep", "--sign", "-", str(bundle)],
        capture_output=True,
        text=True,
    )
    if result.returncode == 0:
        print("  signed (ad-hoc)")
    else:
        print(f"  (could not sign: {result.stderr.strip()})")


def main() -> int:
    parser = argparse.ArgumentParser(description=f"Build {APP_NAME}.app")
    parser.add_argument(
        "--install", action="store_true", help="move the bundle to /Applications"
    )
    args = parser.parse_args()

    if sys.platform != "darwin":
        print("This builder makes a macOS .app bundle.", file=sys.stderr)
        return 1

    if not (ROOT / ".venv" / "bin" / "python").exists():
        print("No .venv found — create it before building.", file=sys.stderr)
        return 1

    dist = ROOT / "dist"
    dist.mkdir(exist_ok=True)
    bundle = build(dist)

    if args.install:
        target = Path("/Applications") / bundle.name
        if target.exists():
            shutil.rmtree(target)
        shutil.move(str(bundle), str(target))
        bundle = target
        print(f"Installed to {bundle}")

    print(f"\nDone. Double-click {bundle}")
    print("It lives in the Dock; closing the window keeps it checking in the background.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
