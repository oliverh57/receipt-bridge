#!/usr/bin/env python3
"""Build `Receipt Bridge.app` — a real macOS menu-bar application.

    python build_app.py              # build into dist/
    python build_app.py --install    # build and move into /Applications

The bundle launches the menu-bar app using this project's virtualenv rather
than embedding its own copy of Python. That is a deliberate choice: Playwright
keeps its Chromium in a shared cache outside any bundle, so a "self-contained"
build would still depend on something external — while being far more fragile.
This way there is one obvious place where the code lives, and the app is a
genuine double-clickable .app with no terminal in sight.

The trade-off: the bundle points at this folder. Move the project and rebuild.
"""

from __future__ import annotations

import argparse
import os
import plistlib
import re
import shutil
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent
APP_NAME = "Receipt Bridge"
BUNDLE_ID = "com.receiptbridge.app"
EXECUTABLE = "ReceiptBridge"

LAUNCHER = """#!/bin/bash
# Launcher for {app_name}. Generated by build_app.py — edit that, not this.
PROJECT="{project}"
PYTHON="$PROJECT/.venv/bin/python"

if [ ! -x "$PYTHON" ]; then
  osascript -e 'display alert "{app_name} can’t start" message "The project folder has moved or its virtualenv is missing.\\n\\nExpected:\\n{project}\\n\\nRe-run build_app.py from wherever the project now lives." as critical'
  exit 1
fi

cd "$PROJECT" || exit 1
mkdir -p "$PROJECT/data"
# A bundle has nowhere to print, so keep a log worth reading when it misbehaves.
exec "$PYTHON" -m app.mac_app >> "$PROJECT/data/app.log" 2>&1
"""


NATIVE_LAUNCHER = r"""// Receipt Bridge launcher. Generated by build_app.py — edit that, not this.
//
// Embeds Python in this executable rather than handing off to Python's own
// app. With a shell-script launcher, macOS saw the running process as
// "Python": the Dock, Cmd-Tab and the app menu said Python, and because the
// system thought Receipt Bridge was not running, opening it again launched a
// second copy. Running Python in-process makes this bundle the real app.
#include <Python.h>
#include <stdio.h>
#include <stdlib.h>
#include <unistd.h>
#include <sys/stat.h>

#define PROJECT   "{project}"
#define VENV_PY   "{venv_python}"
#define LOG_FILE  "{log_file}"

static int fail(const char *what) {{
    char cmd[2048];
    snprintf(cmd, sizeof cmd,
        "osascript -e 'display alert \"Receipt Bridge can’t start\" "
        "message \"%s\\n\\nRe-run build_app.py from the project folder.\" as critical'",
        what);
    system(cmd);
    return 1;
}}

int main(int argc, char **argv) {{
    if (chdir(PROJECT) != 0) return fail("The project folder has moved.");
    if (access(VENV_PY, X_OK) != 0) return fail("The project's .venv is missing.");

    // A bundle has no terminal; keep output somewhere worth reading, and
    // stop it growing without bound: past 2 MB it is moved aside once.
    struct stat st;
    if (stat(LOG_FILE, &st) == 0 && st.st_size > 2 * 1024 * 1024) {{
        rename(LOG_FILE, LOG_FILE ".1");
    }}
    freopen(LOG_FILE, "a", stdout);
    freopen(LOG_FILE, "a", stderr);
    setvbuf(stdout, NULL, _IOLBF, 0);

    PyConfig config;
    PyConfig_InitPythonConfig(&config);
    PyStatus status;
    // Pointing `executable` at the venv's interpreter is what makes Python
    // find .venv/pyvenv.cfg and put the venv's packages on sys.path.
    status = PyConfig_SetBytesString(&config, &config.executable, VENV_PY);
    if (PyStatus_Exception(status)) goto error;
    status = PyConfig_SetBytesString(&config, &config.program_name, VENV_PY);
    if (PyStatus_Exception(status)) goto error;
    status = PyConfig_SetBytesString(&config, &config.run_module, "app.mac_app");
    if (PyStatus_Exception(status)) goto error;
    status = PyConfig_SetBytesArgv(&config, 1, argv);
    if (PyStatus_Exception(status)) goto error;

    status = Py_InitializeFromConfig(&config);
    if (PyStatus_Exception(status)) goto error;
    PyConfig_Clear(&config);
    return Py_RunMain();

error:
    PyConfig_Clear(&config);
    Py_ExitStatusException(status);
}}
"""


def compile_launcher(target: Path) -> bool:
    """Build the native launcher. False means fall back to the script."""
    import sysconfig

    venv_python = ROOT / ".venv" / "bin" / "python"
    config_tool = Path(sysconfig.get_config_var("BINDIR") or "") / (
        f"python{sysconfig.get_python_version()}-config"
    )
    if not config_tool.exists():
        print(f"  (no {config_tool.name}; using the script launcher)")
        return False

    flags = subprocess.run(
        [str(config_tool), "--cflags", "--embed", "--ldflags"],
        capture_output=True, text=True,
    ).stdout.split()
    source = target.with_suffix(".c")
    source.write_text(
        NATIVE_LAUNCHER.format(
            project=ROOT,
            venv_python=venv_python,
            log_file=ROOT / "data" / "app.log",
        ),
        encoding="utf-8",
    )
    result = subprocess.run(
        ["clang", "-O2", "-Wno-unused-result", str(source), "-o", str(target), *flags],
        capture_output=True, text=True,
    )
    source.unlink(missing_ok=True)
    if result.returncode != 0:
        print(f"  (launcher did not compile, using the script: {result.stderr.strip()[:300]})")
        return False
    print("  native launcher compiled")
    return True


